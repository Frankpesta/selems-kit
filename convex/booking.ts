import { v } from "convex/values";
import { internalMutation } from "./_generated/server";
import { internal } from "./_generated/api";
import { todayLagos } from "../lib/dates";
import { appError } from "./lib/errors";
import { freeRoomsOfType } from "./lib/availability";
import { addBookingEvent, occupyNights } from "./lib/bookings";
import { nextRef, sha256Hex } from "./lib/refs";
import {
  bestPrice,
  getSettings,
  offersForStay,
  overridesForStay,
  publishedRoomTypeBySlug,
} from "./lib/stays";
import {
  bookingSearchText,
  guestArgs,
  stayArgs,
  validateGuest,
  validateGuests,
  validateSpecialRequests,
  validateStay,
} from "./lib/validators";
import { bookingPurpose } from "./schema";

export const MAX_ARRIVAL_WINDOW = 40;

/**
 * The booking transaction (docs/04): the only place a website booking is written.
 *
 * Everything from the availability check to the occupancy inserts happens in
 * this one mutation. Convex runs mutations as serialisable transactions, so if
 * two guests race for the last room, the later transaction is retried, sees the
 * room taken and throws SOLD_OUT. Never split the check and the insert.
 */
export const create = internalMutation({
  args: {
    roomTypeSlug: v.string(),
    ...stayArgs,
    guest: guestArgs,
    arrivalWindow: v.optional(v.string()),
    purpose: v.optional(bookingPurpose),
    specialRequests: v.optional(v.string()),
    // Generated by the calling action (real randomness); only its hash is stored.
    manageToken: v.string(),
  },
  handler: async (ctx, args) => {
    // 1. Settings, room type, validation (re-run here: never trust the caller).
    const settings = await getSettings(ctx);
    const roomType = await publishedRoomTypeBySlug(ctx, args.roomTypeSlug);
    const today = todayLagos();
    const nights = validateStay(args, settings, today);
    validateGuests(args, roomType);
    const guest = validateGuest(args.guest);
    const specialRequests = validateSpecialRequests(args.specialRequests);
    const arrivalWindow = args.arrivalWindow?.trim().slice(0, MAX_ARRIVAL_WINDOW) || undefined;

    // 2–3. Re-check availability and assign the first free room.
    const free = await freeRoomsOfType(ctx, roomType._id, args.checkIn, args.checkOut);
    if (free.length === 0) {
      throw appError("SOLD_OUT", `Someone just booked the last ${roomType.name} for these dates.`);
    }
    const room = free[0];

    // 4. Price (including any offer the stay qualifies for).
    const overrides = await overridesForStay(ctx, roomType._id, args.checkIn, args.checkOut);
    const offers = await offersForStay(ctx, args.checkIn, args.checkOut);
    const price = bestPrice(roomType, overrides, offers, args.checkIn, args.checkOut);

    // 5. Reference.
    const ref = await nextRef(ctx, today);

    // 6–7. Insert the booking.
    const now = Date.now();
    const bookingId = await ctx.db.insert("bookings", {
      ref,
      roomTypeId: roomType._id,
      roomId: room._id,
      checkIn: args.checkIn,
      checkOut: args.checkOut,
      nights,
      adults: args.adults,
      children: args.children,
      guest,
      arrivalWindow,
      purpose: args.purpose,
      specialRequests,
      source: "website",
      status: "reserved",
      nightly: price.nightly,
      offerId: price.offer?._id,
      amountDue: price.total,
      amountPaid: 0,
      paymentStatus: "unpaid",
      manageTokenHash: await sha256Hex(args.manageToken),
      searchText: bookingSearchText({ ref, guest }),
      createdAt: now,
      updatedAt: now,
    });

    // 8. Take the room for every night.
    await occupyNights(ctx, bookingId, room._id, args.checkIn, args.checkOut);

    // 9. History.
    await addBookingEvent(
      ctx,
      bookingId,
      "created",
      `Booked online: ${roomType.name}, room ${room.number}, ${nights} night${nights === 1 ? "" : "s"}${price.offer ? ` (${price.offer.title})` : ""}.`,
    );

    // 10. Emails go out after the transaction commits.
    await ctx.scheduler.runAfter(0, internal.emails.bookingConfirmation, {
      bookingId,
      token: args.manageToken,
    });
    await ctx.scheduler.runAfter(0, internal.emails.staffNewBooking, { bookingId });

    return { ref, bookingId };
  },
});
